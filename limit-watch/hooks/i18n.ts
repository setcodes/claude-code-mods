// Начала сообщений о продолжении на всех языках: по ним мод узнаёт свои сообщения в истории.
export const RESUME_HEADS = Object.values(STRINGS).map(s => s.resumeHead)

export function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && (LANGS as readonly string[]).includes(value)
}

// Тег локали (`ru_RU.UTF-8`, `pt-BR`, `zh-Hans-CN`) в язык мода. Пустой, `C` и `POSIX` ничего не говорят о языке.
export function langFromLocale(tag: string | undefined): Lang | null {
  const code = tag?.trim().split(/[-_.@]/)[0]?.toLowerCase()
  if (!code || code === 'c' || code === 'posix') return null
  // Язык без перевода получает английский. Китайский один, упрощённый: для zh-TW и zh-HK тоже он.
  return isLang(code) ? code : 'en'
}
